import { useEffect, useState } from 'react';
import { Pressable, StyleSheet, View } from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { AppHeader } from '../../components/AppHeader';
import { AppText } from '../../components/AppText';
import { HelpNote } from '../../components/HelpNote';
import { PetAvatar } from '../../components/PetAvatar';
import { Screen } from '../../components/Screen';
import { LoadingState } from '../../components/States';
import { usePets } from '../../context/PetContext';
import { CLINICS } from '../../data/mockClinics';
import type { MedicalRecord } from '../../data/mockMedicalRecords';
import { medicalRecordService } from '../../services/medicalRecordService';
import { colors, radii, spacing } from '../../theme';
import type { PetsScreenProps } from '../../navigation/types';

/** PO-39 Medical Record Details */
export function MedicalRecordDetailsScreen({ navigation, route }: PetsScreenProps<'MedicalRecordDetails'>) {
  const { recordId } = route.params;
  const { getPet } = usePets();
  const [record, setRecord] = useState<MedicalRecord | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let active = true;
    void medicalRecordService.getById(recordId).then((entry) => {
      if (!active) return;
      setRecord(entry);
      setLoading(false);
    });
    return () => {
      active = false;
    };
  }, [recordId]);

  if (loading) {
    return (
      <Screen contentStyle={styles.content}>
        <AppHeader title="Medical Record Details" />
        <LoadingState />
      </Screen>
    );
  }

  if (!record) {
    return (
      <Screen contentStyle={styles.content}>
        <AppHeader title="Medical Record Details" />
        <AppText variant="title">This record is no longer available.</AppText>
      </Screen>
    );
  }

  const pet = getPet(record.petId);
  const clinic = CLINICS.find((item) => item.id === record.clinicId);

  const rows: { label: string; value: string }[] = [
    { label: 'CLINIC', value: clinic?.name ?? 'Not recorded' },
    { label: 'ATTENDING VETERINARIAN', value: record.veterinarian ?? 'Not recorded' },
    { label: 'CONSULTATION', value: record.consultation ?? 'Not recorded' },
    { label: 'RECORDED DIAGNOSIS', value: record.diagnosis ?? 'Not recorded' },
    { label: 'TREATMENT', value: record.treatment ?? 'Not recorded' },
    { label: 'PRESCRIPTIONS', value: record.prescriptions ?? 'No prescription attached' },
    { label: 'CLINICAL NOTES', value: record.notes ?? 'Contact the clinic for the complete consultation notes.' },
  ];

  return (
    <Screen contentStyle={styles.content}>
      <AppHeader title="Medical Record Details" />

      <AppText variant="display">{record.title}</AppText>
      <AppText variant="body" color={colors.text.secondary}>
        {medicalRecordService.longDate(record.dateISO)} · Record {record.reference}
      </AppText>

      {pet ? (
        <View style={styles.petRow}>
          <PetAvatar pet={pet} size={56} />
          <View style={styles.flex}>
            <AppText variant="cardTitle">{pet.name}</AppText>
            <AppText variant="caption">
              {pet.species} · {pet.breed} · {pet.ageLabel}
            </AppText>
          </View>
        </View>
      ) : null}

      <View style={styles.card}>
        {rows.map((row) => (
          <View key={row.label} style={styles.row}>
            <AppText variant="small" color={colors.text.secondary} style={styles.rowLabel}>
              {row.label}
            </AppText>
            <AppText variant="body">{row.value}</AppText>
          </View>
        ))}
      </View>

      <Pressable
        accessibilityRole="button"
        onPress={() => navigation.navigate('MedicalRecordAttachments', { recordId: record.id })}
        style={({ pressed }) => [styles.attachmentRow, pressed && styles.pressed]}
      >
        <Ionicons name="document-attach-outline" size={20} color={colors.text.brand} />
        <AppText variant="bodyStrong" style={styles.flex}>
          Attached documents · {record.attachments.length} file{record.attachments.length === 1 ? '' : 's'}
        </AppText>
        <Ionicons name="chevron-forward" size={18} color={colors.text.subtle} />
      </Pressable>

      <HelpNote>
        Demo record · No diagnosis or prescription is generated by VetLink. Only authorized veterinary personnel may
        update clinical records.
      </HelpNote>
    </Screen>
  );
}

const styles = StyleSheet.create({
  content: { gap: spacing.md, paddingBottom: spacing.xxxl },
  petRow: { flexDirection: 'row', alignItems: 'center', gap: spacing.md },
  flex: { flex: 1 },
  card: {
    gap: spacing.md,
    padding: spacing.lg,
    borderRadius: radii.card,
    borderWidth: 1,
    borderColor: colors.surface.border,
    backgroundColor: colors.surface.card,
  },
  row: { gap: 2 },
  rowLabel: { letterSpacing: 0.6 },
  attachmentRow: {
    flexDirection: 'row',
    alignItems: 'center',
    gap: spacing.sm,
    padding: spacing.lg,
    borderRadius: radii.card,
    borderWidth: 1,
    borderColor: colors.surface.border,
    backgroundColor: colors.surface.card,
  },
  pressed: { backgroundColor: colors.surface.subtle },
});
